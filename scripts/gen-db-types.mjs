// Generates lib/supabase/database.types.ts from the local migrations using PGlite,
// in the same shape as `supabase gen types typescript`. Use `pnpm db:types`
// instead once a Supabase project is linked.
import { PGlite } from "@electric-sql/pglite";
import { pg_trgm } from "@electric-sql/pglite/contrib/pg_trgm";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const db = await PGlite.create({ extensions: { pg_trgm } });
await db.exec(readFileSync(join(root, "tests/db/supabase-shim.sql"), "utf8"));
const dir = join(root, "supabase/migrations");
for (const f of readdirSync(dir).filter((x) => x.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(join(dir, f), "utf8"));
}

const enums = (
  await db.query(`
    select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows;
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray) {
  const base = udt.replace(/^_/, "");
  let t;
  if (enumNames.has(base)) t = `Database["public"]["Enums"]["${base}"]`;
  else if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(base)) t = "number";
  else if (base === "bool") t = "boolean";
  else if (["json", "jsonb"].includes(base)) t = "Json";
  else t = "string";
  return isArray ? `${t}[]` : t;
}

const columns = (
  await db.query(`
    select c.table_name, c.column_name, c.is_nullable = 'YES' as nullable,
           (c.column_default is not null or c.is_identity = 'YES') as has_default,
           c.data_type = 'ARRAY' as is_array, c.udt_name
    from information_schema.columns c
    join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.column_name`)
).rows;

const fks = (
  await db.query(`
    select con.conname as name, rel.relname as table_name,
           array_agg(att.attname order by k.ord) as cols,
           frel.relname as ref_table,
           array_agg(fatt.attname order by k.ord) as ref_cols
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    join pg_namespace n on n.oid = rel.relnamespace
    join pg_class frel on frel.oid = con.confrelid
    join pg_namespace fn on fn.oid = frel.relnamespace
    cross join lateral unnest(con.conkey, con.confkey) with ordinality as k(attnum, fattnum, ord)
    join pg_attribute att on att.attrelid = con.conrelid and att.attnum = k.attnum
    join pg_attribute fatt on fatt.attrelid = con.confrelid and fatt.attnum = k.fattnum
    where con.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
    group by con.conname, rel.relname, frel.relname
    order by con.conname`)
).rows;

const uniqueCols = new Set(
  (
    await db.query(`
      select rel.relname as t, array_agg(att.attname) as cols
      from pg_constraint con
      join pg_class rel on rel.oid = con.conrelid
      join pg_namespace n on n.oid = rel.relnamespace
      join pg_attribute att on att.attrelid = con.conrelid and att.attnum = any(con.conkey)
      where con.contype in ('p', 'u') and n.nspname = 'public'
      group by con.conname, rel.relname`)
  ).rows
    .filter((r) => r.cols.length === 1)
    .map((r) => `${r.t}.${r.cols[0]}`),
);

const funcs = (
  await db.query(`
    select p.proname as name,
           pg_get_function_arguments(p.oid) as args,
           p.proretset as retset,
           pg_get_function_result(p.oid) as result,
           coalesce(p.proargnames, '{}') as argnames,
           coalesce(p.proargmodes::text[], '{}') as argmodes,
           (select array_agg(t.typname order by a.ord)
              from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality as a(oid, ord)
              join pg_type t on t.oid = a.oid) as argudts,
           rt.typname as rettype
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype
    where n.nspname = 'public' and rt.typname <> 'trigger'
    order by p.proname`)
).rows;

const tables = [...new Set(columns.map((c) => c.table_name))];
let out = `// Generated by scripts/gen-db-types.mjs — do not edit by hand.
// Regenerate with \`node scripts/gen-db-types.mjs\` (or \`pnpm db:types\` against a linked project).
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: { PostgrestVersion: "13.0.5" };
  public: {
    Tables: {
`;
for (const t of tables) {
  const cols = columns.filter((c) => c.table_name === t);
  const row = cols.map((c) => `          ${c.column_name}: ${tsType(c.udt_name, c.is_array)}${c.nullable ? " | null" : ""};`);
  const ins = cols.map(
    (c) =>
      `          ${c.column_name}${c.nullable || c.has_default ? "?" : ""}: ${tsType(c.udt_name, c.is_array)}${c.nullable ? " | null" : ""};`,
  );
  const upd = cols.map((c) => `          ${c.column_name}?: ${tsType(c.udt_name, c.is_array)}${c.nullable ? " | null" : ""};`);
  const rels = fks
    .filter((f) => f.table_name === t)
    .map(
      (f) => `          {
            foreignKeyName: "${f.name}";
            columns: [${f.cols.map((c) => `"${c}"`).join(", ")}];
            isOneToOne: ${f.cols.length === 1 && uniqueCols.has(`${t}.${f.cols[0]}`)};
            referencedRelation: "${f.ref_table}";
            referencedColumns: [${f.ref_cols.map((c) => `"${c}"`).join(", ")}];
          },`,
    );
  out += `      ${t}: {
        Row: {
${row.join("\n")}
        };
        Insert: {
${ins.join("\n")}
        };
        Update: {
${upd.join("\n")}
        };
        Relationships: [
${rels.join("\n")}
        ];
      };
`;
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;
for (const f of funcs) {
  const names = f.argnames;
  const modes = f.argmodes.length ? f.argmodes : names.map(() => "i");
  const inArgs = [];
  const outCols = [];
  // parse defaults from pg_get_function_arguments
  const argDecls = f.args ? f.args.split(/,\s(?![^()]*\))/) : [];
  names.forEach((n, i) => {
    const mode = modes[i];
    const udt = f.argudts[i];
    const isArr = udt.startsWith("_");
    const type = tsType(udt, isArr);
    if (mode === "i" || mode === "b") {
      const decl = argDecls.find((d) => d.trim().startsWith(n + " ")) ?? "";
      inArgs.push(`          ${n}${/ DEFAULT /i.test(decl) ? "?" : ""}: ${type} | null;`);
    }
    if (mode === "t" || mode === "o") outCols.push(`            ${n}: ${type};`);
  });
  let ret;
  if (outCols.length) ret = `{\n${outCols.join("\n")}\n          }[]`;
  else if (f.rettype === "void") ret = "undefined";
  else ret = tsType(f.rettype, f.rettype.startsWith("_")) + (f.retset ? "[]" : "");
  out += `      ${f.name}: {
        Args: ${inArgs.length ? `{\n${inArgs.join("\n")}\n        }` : "never"};
        Returns: ${ret};
      };
`;
}
out += `    };
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};`).join("\n")}
    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;
writeFileSync(join(root, "lib/supabase/database.types.ts"), out);
console.log(`Wrote ${tables.length} tables, ${funcs.length} functions, ${enums.length} enums`);
